"""
Физические константы и система единиц.

Обоснование выбора единиц
-------------------------

В учебниках (см. [1], [2]) формулы записаны с явными ℏ и m, потому что
учебник должен работать для любых частиц и любых единиц измерения.

В численных расчётах обычно поступают иначе: выбирают систему единиц,
в которой часть фундаментальных констант равна единице. Это не
«упрощение физики» и не потеря общности.

Причина — масштабная инвариантность уравнения Шрёдингера. Если сделать
замену

    x → λx,    t → λ²t,    ε → ε/λ²,    W → W/λ²,    U₀ → U₀/λ²,

то форма уравнения не изменится. Значит, физически важны не абсолютные
значения ℏ, m, x, t, а отношения между ними. Выбор ℏ = 1, m = 1 — это
просто выбор единиц длины, времени и энергии. Никакой информации о
физике при этом не теряется.

Практическое следствие: коэффициент прохождения D зависит не от W, d, ε
по отдельности, а только от безразмерных комбинаций

    W̃ = mWd²/ℏ²,    ε̃ = mεd²/ℏ².

Поэтому мы фиксируем ℏ и m один раз и варьируем только параметры
потенциала (W или U₀, d или a) и начального пакета (ε, b). Частица
считается одной и той же во всех экспериментах.


Что фиксируется, а что варьируется
----------------------------------

Фиксированы (константы, одинаковы для всех конфигураций):
    ℏ  — постоянная Планка,
    m  — масса частицы.

Варьируются (входные параметры модели, меняются от конфигурации
к конфигурации):
    W, d   — высота и ширина барьера,
    U₀, a  — глубина и полуширина ямы,
    ε      — средняя энергия частицы,
    b      — ширина начального волнового пакета.


Переход к системе СИ
-------------------

Если понадобится сравнить результаты с реальной физической частицей
(например, с электроном), достаточно поменять значения в одном месте:

    h_planck = 1.054571817e-34   # Дж·с  (приведённая постоянная Планка)
    m        = 9.1093837015e-31  # кг    (масса электрона)

Весь остальной код остаётся без изменений, потому что везде используются
именно эти переменные, а не числовые литералы.


Ссылки
------
[1] Лыков С.Н. Квантовая механика: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 236 с.
[2] Лыков С.Н., Гасумянц В.Э., Рыков С.А. Квантовая механика. Задачи
    с решениями: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 315 с.
"""

