"""
Потенциалы V(x) для одномерного уравнения Шрёдингера.

В проекте используются два типа потенциала:

    1. Прямоугольный потенциальный барьер (задача 5.4);
    2. Прямоугольная потенциальная яма (задача 5.3).

Оба потенциала кусочно-постоянны: их значение зависит только от того,
в какую пространственную область попала координата x. Это позволяет
записать V(x) в виде набора условий через np.where.

Единицы
-------

В файле physics/constants.py выбрана атомная система единиц:
ℏ = 1, m = 1. Все параметры (W, d, U₀, a) безразмерны, как и сама
координата x.


Потенциал барьера
-----------------

Потенциал прямоугольного барьера высотой W и шириной d:

        ⎧ 0,   x < 0
V(x) =  ⎨ W,   0 ≤ x ≤ d
        ⎩ 0,   x > d

Физический смысл: частица движется слева направо, на пути встречает
область ширины d, в которой её потенциальная энергия выше, чем вне её.
Если энергия частицы ε меньше W, наблюдается туннелирование; если
больше — надбарьерное прохождение с частичным отражением.

Источник: [2], стр. 157, рис. 5.4, задача 5.4.


Потенциал ямы
-------------

Потенциал прямоугольной ямы глубиной U₀ и полушириной a:

        ⎧ 0,     x < -a
V(x) =  ⎨ -U₀,  -a ≤ x ≤ a
        ⎩ 0,     x > a

Физический смысл: частица движется над ямой, внутри которой её
потенциальная энергия ниже, чем снаружи. При определённых энергиях
наблюдается резонансное прохождение D = 1, а волновые функции внутри
ямы обладают определённой чётностью.

Источник: [2], стр. 150, рис. 5.3, задача 5.3.


Ссылки
------
[1] Лыков С.Н. Квантовая механика: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 236 с.
[2] Лыков С.Н., Гасумянц В.Э., Рыков С.А. Квантовая механика. Задачи
    с решениями: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 315 с.
"""

#библиотека для работы с массивами чисел
import numpy as np

#Строка сразу после def, записанная в """...""" — это docstring (документация функции).
#Python её не выполняет, но она:
# доступна через help(V_barrier),
# отображается во всех IDE при наведении курсора

def V_barrier(x, W, d):
    """
    Прямоугольный потенциальный барьер.

        ⎧ 0,   x < 0  или  x > d
V(x) =  ⎨
        ⎩ W,   0 ≤ x ≤ d

    Параметры
    ---------
    x : float или ndarray
        Пространственная координата (может быть массивом).
    W : float
        Высота барьера (W > 0).
    d : float
        Ширина барьера (d > 0).

    Возвращает
    ----------
    V : float или ndarray той же формы, что и x
        Значение потенциала в точке x (или в каждой точке массива x).

    Источник: [2], стр. 157, рис. 5.4, задача 5.4.
    """
    x = np.asarray(x) #превращение входа в numpy-массив
    inside = (x >= 0.0) & (x <= d)
    return np.where(inside, W, 0.0) #np.where(условие, значение_если_истина, значение_если_ложь)


def V_well(x, U0, a):
    """
    Прямоугольная потенциальная яма.

        ⎧ 0,     x < -a  или  x > a
V(x) =  ⎨
        ⎩ -U₀,  -a ≤ x ≤ a

    Параметры
    ---------
    x : float или ndarray
        Пространственная координата.
    U0 : float
        Глубина ямы (U₀ > 0).
    a : float
        Полуширина ямы (a > 0). Полная ширина ямы равна 2a.

    Возвращает
    ----------
    V : float или ndarray той же формы, что и x

    Источник: [2], стр. 150, рис. 5.3, задача 5.3.
    """
    x = np.asarray(x)
    inside = np.abs(x) <= a
    #np.abs — модуль числа, применённый поэлементно
    #Нужно для ямы, потому что условие «внутри ямы» — это |x| ≤ a, то есть -a ≤ x ≤ a
    return np.where(inside, -U0, 0.0) #np.where(условие, значение_если_истина, значение_если_ложь)


