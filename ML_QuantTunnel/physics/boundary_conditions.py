"""
Граничные условия для уравнения Шрёдингера в задаче рассеяния.

Зачем вообще граничные условия
------------------------------

Уравнение Шрёдингера — дифференциальное уравнение в частных производных
второго порядка по x. Чтобы решение было единственным, к нему нужно
добавить:

    - начальное условие (IC)      — что происходит при t = 0;
    - граничные условия (BC)      — что происходит на границах
                                    пространственной области x = ±L.

Без граничных условий решение «убежит» через границы вычислительной
области, и PINN не сойдётся.


Что мы задаём на границах
-------------------------

Мы ограничиваем область x ∈ [-L, L] и требуем, чтобы волновая функция
обнулялась на обеих границах в любой момент времени t:

    ψ(-L, t) = 0,
    ψ(L, t)   = 0     для всех t ∈ [0, T].

Для комплексной ψ = u + iv это эквивалентно четырём действительным
условиям:

    u(-L, t) = 0,    u(L, t) = 0,
    v(-L, t) = 0,    v(L, t) = 0.

Это так называемые граничные условия Дирихле (задание значения
функции на границе, в отличие от условий Неймана — задания производной).


Почему обнуление на границах — это допустимо
--------------------------------------------

Физически «частица прижата к нулю на стенках» означало бы наличие
бесконечных потенциальных стенок при x = ±L. Но в нашей задаче стенок
нет — есть только барьер или яма вблизи нуля. Обнуление ψ(±L, t) = 0
используется как технический приём: мы выбираем L настолько большим,
чтобы волновой пакет за время моделирования T не достигал границ.
Тогда реальное значение ψ(±L, t) пренебрежимо мало, и мы вправе
заменить его нулём.

Условие применимости такого приближения:

    L ≫ |x0| + v_max · T,

где x0 — начальное положение центра пакета (x0 < 0),
     v_max = √(2m·ε_max)/m — максимальная скорость частицы,
     T — полное время моделирования.

Смысл: даже самый быстрый пакет не должен успеть дойти до границы,
иначе нулевое условие на границе «отразит» его обратно и исказит
физически правильную картину.

Источник: [1], стр. 110 (обсуждение граничных условий).


Ссылки
------
[1] Лыков С.Н. Квантовая механика: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 236 с.
[2] Лыков С.Н., Гасумянц В.Э., Рыков С.А. Квантовая механика. Задачи
    с решениями: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 315 с.
"""

import numpy as np

from physics.constants import h_planck, m


def boundary_values(x):
    """
    Значения граничных условий в точке x.

    Граничные условия требуют u = v = 0 на обеих границах области.
    Функция возвращает пару (u_bc, v_bc) — оба нули.

    Зачем нужна такая «нулевая» функция, если она тривиальна?
    Затем, что в коде PINN её удобно вызывать в одном месте:
    там, где мы задаём BC, мы подставляем эту функцию, а не хардкодим
    нули в четырёх разных местах. Если однажды BC изменятся (например,
    на периодические), поправить придётся только здесь.

    Источник: [1], стр. 110.
    """
    x = np.asarray(x)
    zeros = np.zeros_like(x, dtype=float)
    return zeros, zeros


def generate_boundary_points(L, T, n_left=200, n_right=200, seed=0):
    """
    Генерирует точки на границах области для PINN.

    Границы — это два отрезка в пространстве-времени:
        левая:   x = -L, t ∈ [0, T];
        правая:  x = +L, t ∈ [0, T].

    Точки распределяются равномерно по t. На каждой границе — n_left
    (соответственно n_right) точек.

    Параметры
    ---------
    L : float
        Полуширина пространственной области. Границы: x = ±L.
    T : float
        Полное время моделирования.
    n_left, n_right : int
        Число точек на левой и правой границах.
    seed : int
        Seed для воспроизводимости (не критично при равномерной сетке,
        но полезно, если позже заменить её на случайную).

    Возвращает
    ----------
    points : ndarray формы (n_left + n_right, 2)
        Каждая строка — точка (x, t) на одной из границ.
        Первые n_left строк — на левой границе x = -L,
        следующие n_right строк — на правой границе x = +L.
    sides : ndarray формы (n_left + n_right,)
        Метка стороны: -1 для левой границы, +1 для правой.
        Может пригодиться, если мы захотим задать разные BC на разных
        границах (например, поглощающие слои слева и справа).
    """
    t_left = np.linspace(0.0, T, n_left)
    t_right = np.linspace(0.0, T, n_right)

    x_left = np.full_like(t_left, -L)
    x_right = np.full_like(t_right, +L)

    pts_left = np.column_stack([x_left, t_left])
    pts_right = np.column_stack([x_right, t_right])
    points = np.vstack([pts_left, pts_right])

    sides = np.concatenate([
        np.full(n_left, -1, dtype=int),
        np.full(n_right, +1, dtype=int),
    ])

    return points, sides


def check_L_sufficient(L, x0, b, eps, T):
    """
    Проверяет, что L достаточно велико для корректности BC ψ(±L) = 0.

    Критерий: даже самый быстрый «край» гауссова пакета, движущийся
    со скоростью v = p/m, не должен за время T дойти до границы x = L.

    Максимальная скорость пакета оценивается как скорость центра плюс
    несколько «сигм» по импульсному распределению. Здесь используется
    простая оценка:

        v_max ≈ p_center/m + 3·δp/m,
        δp = ℏ/(√2 · b)   — среднеквадратичный разброс импульса.

    Коэффициент 3 соответствует примерно трём стандартным отклонениям
    гауссова распределения. Это практическая оценка «разумной
    границы», а не строгий критерий.

    Параметры
    ---------
    L : float
        Полуширина области (см. описание модуля).
    x0 : float
        Начальное положение центра пакета (x0 < 0).
    b : float
        Ширина пакета.
    eps : float
        Средняя энергия частицы.
    T : float
        Полное время моделирования.

    Возвращает
    ----------
    ok : bool
        True, если L достаточно велико.
    info : dict
        Диагностика: значения v_max, правого края траектории и т. д.
    """
    k_center = np.sqrt(2.0 * m * eps) / h_planck
    v_center = h_planck * k_center / m

    # Разброс импульса из соотношения неопределённостей для гауссиана.
    delta_p = h_planck / (np.sqrt(2.0) * b)
    delta_v = delta_p / m

    v_max = v_center + 3.0 * delta_v
    x_reach = x0 + v_max * T

    ok = x_reach < L
    info = dict(
        v_center=v_center,
        delta_v=delta_v,
        v_max=v_max,
        x_reach=x_reach,
        L=L,
        margin=L - x_reach,
    )
    return ok, info


# ---------------------------------------------------------------------------
# Самопроверочный блок.
# Запускается только при прямом вызове файла:
#     python physics/boundary_conditions.py
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    # --- Тест 1. Значения граничных условий ---
    x = np.array([-5.0, 0.0, 5.0])
    u_bc, v_bc = boundary_values(x)
    print("boundary_values(x):")
    print(f"  u_bc = {u_bc}")
    print(f"  v_bc = {v_bc}")
    print()

    # --- Тест 2. Точки на границах ---
    L, T = 20.0, 5.0
    points, sides = generate_boundary_points(L, T, n_left=4, n_right=4)
    print(f"generate_boundary_points(L={L}, T={T}, n_left=4, n_right=4):")
    for (x_pt, t_pt), side in zip(points, sides):
        side_str = "left " if side == -1 else "right"
        print(f"  ({x_pt:+.1f}, {t_pt:.2f})  [{side_str}]")
    print()

    # --- Тест 3. Проверка достаточности L ---
    # Параметры задачи, для которой, скорее всего, L = 20 хватит.
    ok, info = check_L_sufficient(
        L=20.0, x0=-5.0, b=1.0, eps=0.5, T=5.0,
    )
    print("check_L_sufficient(L=20, x0=-5, b=1, eps=0.5, T=5):")
    print(f"  v_center = {info['v_center']:.4f}")
    print(f"  v_max    = {info['v_max']:.4f}")
    print(f"  x_reach  = {info['x_reach']:.4f}")
    print(f"  margin   = {info['margin']:.4f}")
    print(f"  L достаточно: {ok}")
    print()

    # --- Тест 4. Заведомо недостаточное L ---
    ok, info = check_L_sufficient(
        L=2.0, x0=-1.0, b=1.0, eps=2.0, T=10.0,
    )
    print("check_L_sufficient(L=2, x0=-1, b=1, eps=2, T=10):")
    print(f"  x_reach = {info['x_reach']:.4f}, L = {info['L']}, "
          f"L достаточно: {ok}")