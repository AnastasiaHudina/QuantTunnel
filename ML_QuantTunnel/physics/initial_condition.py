if __name__ == "__main__":
    x = np.linspace(-30.0, 30.0, 200_000)

    x0 = -5.0
    b = 1.0
    eps = 0.5

    print(f"k0_from_energy(eps={eps}) = {k0_from_energy(eps):.6f}")
    print(f"norm_constant(b={b})       = {norm_constant(b):.6f}")
    print()

    norm = check_norm(x, x0, b, eps)
    print(f"∫ |ψ|² dx = {norm:.10f}")
    print(f"|norm - 1| = {abs(norm - 1):.4e}")
    print(f"norm = {norm!r}")  # покажет полное repr-представление