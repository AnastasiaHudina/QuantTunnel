"""
Начальное условие для уравнения Шрёдингера — гауссов волновой пакет.

В момент t = 0 частица задаётся гауссовым волновым пакетом, движущимся
слева направо. В общем виде (как в задачнике):

    ψ(x) = C · exp( -(x - x₀)² / (2b²) + i·k₀·x )

где:
    b   — ширина пакета,
    x₀  — начальное положение центра (x₀ < 0, слева от барьера/ямы),
    k₀  — волновое число,
    C   — нормировочный множитель, который нужно найти.


Нормировочный множитель
-----------------------

Условие нормировки:

    ∫ |ψ(x)|² dx = 1.

Вычисляем |ψ|²:

    |ψ|² = |C|² · exp( -(x - x₀)² / b² ).

Интеграл по всей оси:

    ∫ exp( -(x - x₀)² / b² ) dx = b·√π = √(π b²).

Тогда

    |C|² · √(π b²) = 1    ⇒    |C|² = 1 / √(π b²).

Извлекаем квадратный корень:

    |C| = (π b²)^(-1/4).

Итоговое нормированное начальное условие:

    ψ(x, 0) = (π b²)^(-1/4) · exp( -(x - x₀)² / (2b²) + i·k₀·x ).

Источник: [2], стр. 110–111, задача 4.1; решение задачи — стр. 114–115.


Связь k₀ с энергией
-------------------

В задачнике 4.1 волновое число k₀ связано с импульсом p₀ как
k₀ = p₀/ℏ. В нашем проекте мы задаём энергию ε частицы, а не импульс.
Для свободной частицы (вне области потенциала):

    ε = p² / (2m)  ⇒  p = √(2m·ε)  ⇒  k₀ = √(2m·ε) / ℏ.

Это и используется ниже в функции k0_from_energy.

Источник: [2], стр. 117–119, задача 4.2, формулы (4), (5).


Комплексная функция
-------------------

PINN работает с действительными числами, поэтому волновую функцию
представляем как пару:

    ψ(x, 0) = u(x, 0) + i·v(x, 0),

где u = Re(ψ), v = Im(ψ).

Для начального условия:

    u(x, 0) = |C| · exp( -(x - x₀)² / (2b²) ) · cos(k₀·x),
    v(x, 0) = |C| · exp( -(x - x₀)² / (2b²) ) · sin(k₀·x).

Это соответствует:

    ψ = |C| · exp( -(x-x₀)² / (2b²) ) · ( cos(k₀x) + i·sin(k₀x) )
      = |C| · exp( -(x-x₀)² / (2b²) + i·k₀·x ).


Ссылки
------
[1] Лыков С.Н. Квантовая механика: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 236 с.
[2] Лыков С.Н., Гасумянц В.Э., Рыков С.А. Квантовая механика. Задачи
    с решениями: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 315 с.
"""

import numpy as np

from physics.constants import h_planck, m


def k0_from_energy(eps):
    """
    Волновое число свободной частицы, соответствующее средней энергии ε.

        k₀ = √(2m·ε) / ℏ

    Параметры
    ---------
    eps : float или ndarray
        Средняя энергия частицы (в атомных единицах ε > 0).

    Возвращает
    ----------
    k0 : float или ndarray той же формы, что и eps

    Источник: [2], стр. 117–119, задача 4.2, формулы (4), (5).
    """
    return np.sqrt(2.0 * m * np.asarray(eps)) / h_planck


def norm_constant(b):
    """
    Нормировочный множитель гауссова пакета.

        |C| = (π b²)^(-1/4)

    Параметры
    ---------
    b : float
        Ширина пакета (b > 0).

    Возвращает
    ----------
    C : float
        Множитель, обеспечивающий ∫ |ψ|² dx = 1.

    Источник: [2], стр. 114–115, решение задачи 4.1.
    """
    return (np.pi * b ** 2) ** (-0.25) #np.pi - Число π≈3.14159...


def psi_initial(x, x0, b, eps):
    """
    Комплексная волновая функция гауссова пакета в момент t = 0.

        ψ(x, 0) = (π b²)^(-1/4) · exp( -(x-x₀)² / (2b²) + i·k₀·x )

    Параметры
    ---------
    x : float или ndarray
        Пространственная координата.
    x0 : float
        Начальное положение центра пакета (x₀ < 0).
    b : float
        Ширина пакета (b > 0).
    eps : float
        Средняя энергия частицы (ε > 0).

    Возвращает
    ----------
    psi : complex или ndarray комплексных чисел
        Значение ψ(x, 0).

    Источник: [2], стр. 110–111, задача 4.1.
    """
    x = np.asarray(x)
    k0 = k0_from_energy(eps)
    C = norm_constant(b)
    envelope = np.exp(-(x - x0) ** 2 / (2.0 * b ** 2))
    phase = np.exp(1j * k0 * x) #1j — это мнимая единица i в Python
    #Результат np.exp(1j * k0 * x) — массив комплексных чисел, по формуле Эйлера
    return C * envelope * phase


def u_initial(x, x0, b, eps):
    """
    Действительная часть начальной волновой функции:

        u(x, 0) = Re ψ(x, 0).

    Источник: [1], стр. 109, формула (2.164).
    """
    return np.real(psi_initial(x, x0, b, eps))


def v_initial(x, x0, b, eps):
    """
    Мнимая часть начальной волновой функции:

        v(x, 0) = Im ψ(x, 0).

    Источник: [1], стр. 109, формула (2.164).
    """
    return np.imag(psi_initial(x, x0, b, eps))

#np.real(z) — то же, что Re(z)
#np.imag(z) — то же, что Im(z)

def check_norm(x, x0, b, eps):
    """
    Численная проверка нормировки гауссова пакета.

        ∫ |ψ(x, 0)|² dx ≈ 1

    Параметры
    ---------
    x : ndarray
        Сетка, на которой выполняется интегрирование. Должна быть
        достаточно широкой и плотной, чтобы пакет был полностью
        покрыт.

    Возвращает
    ----------
    norm : float
        Значение интеграла ∫ |ψ|² dx.
    """
    psi = psi_initial(x, x0, b, eps)
    integrand = np.abs(psi) ** 2

    # Безопасный fallback для разных версий NumPy:
    # np.trapezoid появился в NumPy 2.0, до этого функция называлась np.trapz
    try:
        return np.trapezoid(integrand, x)  # NumPy 2.0+
    except AttributeError:
        return np.trapz(integrand, x)  # NumPy < 2.0

    #trapezoid - это численное интегрирование методом трапеций.
    #Первый аргумент — массив значений подынтегральной функции, второй — сетка по x.
    #Функция возвращает число (или массив, если интегрирование по одной оси многомерного массива).


