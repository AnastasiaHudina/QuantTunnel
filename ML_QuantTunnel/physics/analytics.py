"""
Аналитические формулы для коэффициента прохождения D.

Здесь собраны аналитические выражения для коэффициента прохождения
частицы через прямоугольный барьер и прямоугольную яму. Эти формулы
используются для валидации PINN: мы сравниваем D, полученный из
обученной сети, с D, посчитанным по формулам ниже.

Физическая постановка
---------------------

Мы рассматриваем стационарную задачу рассеяния: частица с энергией ε
падает слева на потенциал V(x). Ищем коэффициент прохождения D —
отношение плотности потока прошедших частиц к плотности потока
падающих. Для прямоугольных потенциалов D находится аналитически
методом спивания волновых функций на границах.


Режимы для барьера
------------------

Для барьера высотой W и шириной d возможны два качественно разных
режима в зависимости от соотношения энергии ε и высоты W:

    1. ε < W — туннелирование. Частица проникает сквозь барьер
       с экспоненциально малой вероятностью.
    2. ε > W — надбарьерное прохождение. Частица проходит над
       барьером, но есть вероятность отражения.

Аналитические формулы для обоих случаев приводятся ниже.


Режим для ямы
-------------

Для ямы глубиной U₀ и полушириной a мы рассматриваем случай ε > 0,
когда частица движется над ямой. При определённых энергиях
наблюдается резонансное прохождение: D = 1.


Единицы
-------

В файле physics/constants.py выбрана атомная система единиц:
ℏ = 1, m = 1. Все волновые числа k, κ и коэффициент D безразмерны.


Ссылки
------
[1] Лыков С.Н. Квантовая механика: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 236 с.
[2] Лыков С.Н., Гасумянц В.Э., Рыков С.А. Квантовая механика. Задачи
    с решениями: учеб. пособие.
    СПб.: Изд-во Политехн. ун-та, 2008. — 315 с.
"""

import numpy as np

from physics.constants import h_planck, m


def k_free(eps):
    """
    Волновое число свободной частицы с энергией ε.

        k = √(2m·ε) / ℏ

    Используется как снаружи барьера, так и снаружи ямы.

    Источник: [2], стр. 149, задача 5.2; стр. 158, задача 5.4.
    """
    return np.sqrt(2.0 * m * np.asarray(eps)) / h_planck


def kappa_barrier(W, eps):
    """
    Мнимое волновое число под барьером (ε < W).

        κ = √( 2m·(W - ε) ) / ℏ

    Появляется в решении под барьером в виде e^(±κx). Именно κ
    определяет глубину проникновения волновой функции в барьер.

    Источник: [2], стр. 158, задача 5.4, формула (6).
    """
    return np.sqrt(2.0 * m * np.asarray(W - eps)) / h_planck


def D_barrier_below_W(eps, W, d):
    """
    Коэффициент прохождения для барьера при ε < W (туннелирование).

        D = [ 1 + (k² + κ²)² / (4 k² κ²) · sinh²(κ d) ]^(-1)

    где
        k = √(2mε) / ℏ,
        κ = √(2m(W - ε)) / ℏ.

    Параметры
    ---------
    eps : float или ndarray
        Энергия частицы. Должна удовлетворять условию 0 < ε < W.
    W : float или ndarray
        Высота барьера.
    d : float или ndarray
        Ширина барьера.

    Возвращает
    ----------
    D : float или ndarray той же формы
        Коэффициент прохождения, 0 ≤ D ≤ 1.

    Источник: [2], стр. 158, задача 5.4, формула (5);
              также [1], стр. 131, формула (3.47).
    """
    k = k_free(eps)
    kappa = kappa_barrier(W, eps)
    factor = (k ** 2 + kappa ** 2) ** 2 / (4.0 * k ** 2 * kappa ** 2)
    return 1.0 / (1.0 + factor * np.sinh(kappa * d) ** 2)


def D_barrier_above_W(eps, W, d):
    """
    Коэффициент прохождения для барьера при ε > W (надбарьерное
    прохождение).

        D = [ 1 + (k₁² - k₂²)² / (4 k₁² k₂²) · sin²(k₂ d) ]^(-1)

    где
        k₁ = √(2mε) / ℏ      — снаружи барьера,
        k₂ = √(2m(ε - W)) / ℏ — под барьером (действительное число).

    Параметры
    ---------
    eps : float или ndarray
        Энергия частицы. Должна удовлетворять условию ε > W.
    W : float
        Высота барьера.
    d : float
        Ширина барьера.

    Возвращает
    ----------
    D : float или ndarray
        Коэффициент прохождения.

    Источник: [2], стр. 149, задача 5.2, формула (8).
    """
    k1 = k_free(eps)
    k2 = np.sqrt(2.0 * m * np.asarray(eps - W)) / h_planck
    factor = (k1 ** 2 - k2 ** 2) ** 2 / (4.0 * k1 ** 2 * k2 ** 2)
    return 1.0 / (1.0 + factor * np.sin(k2 * d) ** 2)


def D_well(eps, U0, a):
    """
    Коэффициент прохождения для прямоугольной ямы при ε > 0.

        D = [ 1 + (k₁² - k₂²)² / (4 k₁² k₂²) · sin²(2 k₂ a) ]^(-1)

    где
        k₁ = √(2mε) / ℏ         — снаружи ямы,
        k₂ = √(2m(ε + U₀)) / ℏ  — внутри ямы.

    Параметры
    ---------
    eps : float или ndarray
        Энергия частицы (ε > 0).
    U0 : float
        Глубина ямы (U₀ > 0).
    a : float
        Полуширина ямы. Полная ширина ямы равна 2a.

    Возвращает
    ----------
    D : float или ndarray
        Коэффициент прохождения.

    Источник: [2], стр. 150, задача 5.3, формула (2).
    """
    k1 = k_free(eps)
    k2 = np.sqrt(2.0 * m * np.asarray(eps + U0)) / h_planck
    factor = (k1 ** 2 - k2 ** 2) ** 2 / (4.0 * k1 ** 2 * k2 ** 2)
    return 1.0 / (1.0 + factor * np.sin(2.0 * k2 * a) ** 2)


def resonance_energies(U0, a, n_max=5):
    """
    Энергии резонансного прохождения над ямой.

        Условие резонанса:  2 k₂ a = π n,   n = 1, 2, 3, ...

    Отсюда:
        k₂ = π n / (2a),
        ε + U₀ = ℏ² k₂² / (2m)   ⇒   ε = ℏ² π² n² / (8 m a²) - U₀.

    Возвращает только те энергии, для которых ε > 0.

    Параметры
    ---------
    U0 : float
        Глубина ямы (U₀ > 0).
    a : float
        Полуширина ямы.
    n_max : int
        Верхняя граница для числа n.

    Возвращает
    ----------
    eps_list : ndarray
        Массив энергий εₙ, соответствующих резонансам.
        Только те, для которых εₙ > 0.

    Источник: [2], стр. 152, задача 5.3, пункт (6).
    """
    n = np.arange(1, n_max + 1)
    eps = (h_planck ** 2) * (np.pi ** 2) * (n ** 2) / (8.0 * m * a ** 2) - U0
    return eps[eps > 0.0]


