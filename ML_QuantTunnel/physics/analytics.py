if __name__ == "__main__":
    # --- Тест 1. Туннелирование через барьер (ε < W) ---
    eps, W, d = 0.5, 1.0, 1.0
    print(f"D_barrier_below_W(eps={eps}, W={W}, d={d}) = "
          f"{D_barrier_below_W(eps, W, d):.6f}")

    # --- Тест 2. Надбарьерное прохождение (ε > W) ---
    eps, W, d = 1.5, 1.0, 1.0
    print(f"D_barrier_above_W(eps={eps}, W={W}, d={d}) = "
          f"{D_barrier_above_W(eps, W, d):.6f}")

    # --- Тест 3. Резонанс в яме: подбираем ε так, чтобы D = 1 ---
    U0, a = 1.0, 1.0
    resonances = resonance_energies(U0, a, n_max=3)
    print()
    print(f"Резонансные энергии для U0={U0}, a={a}: {resonances}")

    for eps_res in resonances:
        D = D_well(eps_res, U0, a)
        print(f"  ε = {eps_res:.6f}  →  D = {D:.10f}  (ожидается 1)")

    # --- Тест 4. Яма вдали от резонанса ---
    eps, U0, a = 0.7, 1.0, 1.0
    print()
    print(f"D_well(eps={eps}, U0={U0}, a={a}) = "
          f"{D_well(eps, U0, a):.6f}")